def main():
    root=Path('data/v2')
    target=root/'train.jsonl'
    if target.exists():
        raise FileExistsError('拒绝覆盖既有训练集')
    rows=[json.loads(x) for x in Path('data/train.jsonl').read_text(encoding='utf-8').splitlines()]
    for row in rows:
        row['historical_id']=row['id']
        row['category']='技术解释'
    for category,pairs in [('技术解释',TECH),('指令与格式',FORMATS),('不确定性处理',UNCERTAIN)]:
        for question,answer in pairs:
            rows.append(dict(source='self-authored-synthetic-v2-training',category=category,
                             messages=[dict(role='user',content=question),dict(role='assistant',content=answer)]))
    for turns,answer in MULTI:
        messages=[dict(role='user' if i%2==0 else 'assistant',content=text) for i,text in enumerate(turns)]
        messages.append(dict(role='assistant',content=answer))
        rows.append(dict(source='self-authored-synthetic-v2-training',category='多轮上下文',messages=messages))
    assert len(rows)==100
    for i,row in enumerate(rows,1):
        row['id']=f'v2_train_{i:03d}'
    content=''.join(json.dumps(x,ensure_ascii=False)+'\n' for x in rows).encode('utf-8')
    target.write_bytes(content)
    result=dict(count=100,retained=32,new=68,sha256=hashlib.sha256(content).hexdigest(),
                notes='生成器不读取新验证或新测试；训练监督最后一轮助手目标。')
    (root/'training-manifest.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(result,ensure_ascii=False,indent=2))


if __name__=='__main__':
    main()
