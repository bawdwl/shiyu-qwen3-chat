def main():
    root = Path('data')
    root.mkdir(exist_ok=True)
    for split, pairs in [('train', TRAIN), ('validation', VALIDATION)]:
        target = root / f'{split}.jsonl'
        if target.exists():
            raise FileExistsError(f'拒绝覆盖已有数据：{target}')
        records = [dict(id=f'{split}_{i:03d}', source='self-authored-synthetic-v1',
                        messages=[dict(role='user', content=q), dict(role='assistant', content=a)])
                   for i, (q, a) in enumerate(pairs, 1)]
        target.write_text(''.join(json.dumps(x, ensure_ascii=False) + '\n' for x in records), encoding='utf-8')
        print(f'{target}: {len(records)} samples')


if __name__ == '__main__':
    main()
